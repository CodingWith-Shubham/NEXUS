"""JARVIS - Pipecat Voice Agent.

This bot uses a realtime pipeline: Speech-to-Speech with integrated LLM

Generated by Pipecat CLI

Required AI services:
- Gemini_Live (Realtime Speech-to-Speech)

Run the bot using::
    uv run bot.py
"""

import os
from datetime import UTC, datetime

from dotenv import load_dotenv
from loguru import logger
from pipecat.audio.vad.silero import SileroVADAnalyzer
from pipecat.evals.transport import EvalTransportParams
from pipecat.frames.frames import LLMRunFrame
from pipecat.pipeline.pipeline import Pipeline
from pipecat.pipeline.worker import PipelineParams, PipelineWorker
from pipecat.processors.aggregators.llm_context import LLMContext
from pipecat.processors.aggregators.llm_response_universal import (
    LLMContextAggregatorPair,
    LLMUserAggregatorParams,
)
from pipecat.processors.frameworks.rtvi.frames import RTVIServerMessageFrame
from pipecat.runner.types import RunnerArguments
from pipecat.runner.utils import create_transport
from pipecat.services.google.gemini_live.llm import GeminiLiveLLMService
from pipecat.transports.base_transport import BaseTransport, TransportParams
from pipecat.workers.runner import WorkerRunner

from jarvis.announcer import Announcer
from jarvis.app import build_core
from jarvis.prompts import voice_instruction
from jarvis.search import SearchSourceRecorder, voice_tools_schema
from jarvis.sessions import GREETING, build_session_context, summarize_and_save
from jarvis.skills import ToolContext
from jarvis.store import SupabaseStore
from jarvis.voice_language import apply_transcription_hints

load_dotenv(override=True)


async def run_bot(transport: BaseTransport, runner_args: RunnerArguments) -> None:
    """Run the voice bot for this session.

    Args:
        transport: The transport for this session, built by ``create_transport``
            (or by hand for the dial-out/SIP production flows).
        runner_args: Runner session arguments. Carries the request ``body``
            (e.g. dial-out settings, SIP call details) and ``session_id``; the
            standard web/telephony pipelines don't need it.
    """
    logger.info("Starting bot")
    started_at = datetime.now(UTC)

    # JARVIS core: skill packs from jarvis.toml, their tools behind the approval gate.
    core = build_core()
    config = core.config
    store = await SupabaseStore.from_env()
    tool_ctx = ToolContext(
        store=store,
        registry=core.registry,
        source="voice",
        session_id=runner_args.session_id,
        timezone=config.tz(),
        config=config,
    )
    logger.info(f"Voice tools: {core.registry.voice_tool_names()}")

    # Date and time, recent conversation summaries, remembered facts.
    session_context = await build_session_context(store, config, core.packs)

    # Transcribe the user with their language hints (see jarvis.voice_language).
    apply_transcription_hints(config.languages)

    # Realtime LLM service (handles STT, LLM, and TTS internally)
    llm = GeminiLiveLLMService(
        api_key=os.getenv("GOOGLE_API_KEY"),
        settings=GeminiLiveLLMService.Settings(
            model=os.getenv("GOOGLE_MODEL"),
            voice=os.getenv("GOOGLE_VOICE_ID"),
            language=config.languages[0] if config.languages else "en-US",
            system_instruction=voice_instruction(
                core.packs,
                web_search=config.web_search,
                session_context=session_context,
            ),
        ),
    )

    # Tools can send things to the browser (e.g. web search sources) as RTVI messages.
    async def notify_client(data: dict) -> None:
        await llm.push_frame(RTVIServerMessageFrame(data=data))

    tool_ctx.notify = notify_client

    # Gemini Live fixes its tool set for the session, so every voice tool (and
    # Google Search, in "live" web_search mode) is listed up front.
    context = LLMContext(
        tools=voice_tools_schema(
            core.registry.voice_tools(tool_ctx), google_search=config.web_search == "live"
        )
    )
    user_aggregator, assistant_aggregator = LLMContextAggregatorPair(
        context,
        user_params=LLMUserAggregatorParams(vad_analyzer=SileroVADAnalyzer()),
    )

    # Pipeline - assembled from reusable components
    pipeline = Pipeline(
        [
            transport.input(),
            user_aggregator,
            llm,
            SearchSourceRecorder(llm, store, runner_args.session_id),
            transport.output(),
            assistant_aggregator,
        ]
    )

    worker = PipelineWorker(
        pipeline,
        params=PipelineParams(
            enable_metrics=True,
            enable_usage_metrics=True,
        ),
        observers=[],
    )

    runner = WorkerRunner(handle_sigint=runner_args.handle_sigint)

    await runner.add_workers(worker)

    # Speaks up when a background task finishes or the worker needs approval.
    announcer = Announcer(store, llm, poll_secs=core.config.announce_poll_secs)

    @worker.rtvi.event_handler("on_client_ready")
    async def on_client_ready(rtvi):
        # Kick off the conversation
        context.add_message({"role": "developer", "content": GREETING})
        await worker.queue_frames([LLMRunFrame()])
        announcer.start()

    @transport.event_handler("on_client_connected")
    async def on_client_connected(transport, client):
        logger.info("Client connected")

    @transport.event_handler("on_client_disconnected")
    async def on_client_disconnected(transport, client):
        logger.info("Client disconnected")
        await announcer.stop()
        await runner.cancel()

    await runner.run()

    # The session is over (however it ended): leave a summary for the next one.
    try:
        await summarize_and_save(
            store,
            context,
            session_id=runner_args.session_id,
            started_at=started_at,
            llm=core.llm,
        )
    except Exception as e:
        logger.error(f"Could not save the session summary: {e}")


async def bot(runner_args: RunnerArguments):
    """Main bot entry point."""
    transport_params = {
        "webrtc": lambda: TransportParams(
            audio_in_enabled=True,
            audio_out_enabled=True,
        ),
        # Behavioral evals: `pipecat eval` drives this bot through its eval transport.
        "eval": lambda: EvalTransportParams(
            audio_in_enabled=True,
            audio_out_enabled=True,
        ),
    }

    transport = await create_transport(runner_args, transport_params)

    await run_bot(transport, runner_args)


async def _oauth():
    """The Google sign-in handler for the /auth routes, built on first use."""
    global _OAUTH
    if _OAUTH is None:
        from jarvis.config import load_config
        from jarvis.oauth import GoogleOAuth

        config = load_config()
        _OAUTH = GoogleOAuth.from_env(
            await SupabaseStore.from_env(),
            redirect_uri=config.oauth_redirect_uri,
            sign_in_url=config.oauth_sign_in_url,
        )
    return _OAUTH


_OAUTH = None


if __name__ == "__main__":
    from pipecat.runner.run import app, main

    from jarvis.auth_routes import register_auth_routes

    # Google sign-in on the same server: /auth/google, /auth/google/callback, /auth/status.
    register_auth_routes(app, _oauth)
    main()
